export function getIndiaPlace(slug: string) {
  return indiaPlaces.find((place) => place.slug === slug);
}

export function getIndiaPlaceMedia(place: TripPlace) {
  return place.mediaIds.flatMap((id) => mediaFor([id]));
}

export function getIndiaDayId(date: string) {
  const dates = ["2018-09-02", "2018-09-03", "2018-09-04", "2018-09-05", "2018-09-06", "2018-09-07", "2018-09-08", "2018-09-09", "2018-09-10"];
  const index = dates.indexOf(date);
  return `day-${String(index < 0 ? 0 : index).padStart(2, "0")}`;
}
