import mediaManifestJson from "./india-media-manifest.json";
import type { IndiaMediaManifest, MediaItem, TripPlace } from "@/types/travel";

const manifest = mediaManifestJson as IndiaMediaManifest;

function recordsFor(fragments: string[]) {
  return manifest.files.filter((record) => record.imported && record.src && fragments.some((fragment) => record.id.includes(fragment)));
}

function mediaFor(fragments: string[]): MediaItem[] {
  const records = recordsFor(fragments);
  return records.map((record) => ({
    id: record.id,
    src: record.src,
    thumbnailSrc: record.thumbnailSrc,
    alt: mediaAlt(record),
    type: record.type,
    width: record.width,
    height: record.height,
    aspectRatio: record.aspectRatio,
    orientation: record.orientation,
    captureDate: record.captureDate,
    captureTime: record.captureTime,
    fit: record.fit ?? "contain",
    city: record.city,
    dayKey: record.dayKey,
    phase: record.phase,
    poster: record.type === "video" ? records.find((item) => item.type === "image")?.src : undefined,
  }));
}

function mediaAlt(record: IndiaMediaManifest["files"][number]) {
  const places = (record.editorialPlaceIds ?? []).map((id) => indiaPlaces.find((place) => place.id === id)).filter(Boolean);
  if (places.length > 0) return `${places.map((place) => place?.name).join(" y ")} en ${places[0]?.city ?? record.city}`;
  return `Escena del recorrido en ${record.city}`;
}

function idsFor(fragments: string[]) {
  return recordsFor(fragments).map((record) => record.id);
}

